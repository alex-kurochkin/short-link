<?php

use App\Contracts\CodeUniquenessChecker;

/*
|--------------------------------------------------------------------------
| Длина кода короткой ссылки
|--------------------------------------------------------------------------
|
| Количество символов в генерируемом коде короткой ссылки.
| Допустимые значения: от 4 до 10.
|
*/
$length = (int) env('SHORT_LINK_CODE_LENGTH', 6);

if ($length < 4 || $length > 10) {
    throw new \InvalidArgumentException(
        "Недопустимая длина кода SHORT_LINK_CODE_LENGTH: {$length}. Допустимые значения: от 4 до 10."
    );
}

/*
|--------------------------------------------------------------------------
| Реализация проверки уникальности кода
|--------------------------------------------------------------------------
|
| Укажите FQCN реализации интерфейса App\Contracts\CodeUniquenessChecker.
|
| Доступно:
|   - App\Services\CodeCheckers\EloquentCodeUniquenessChecker::class
|   - App\Services\CodeCheckers\CacheCodeUniquenessChecker::class
|
*/
$checker = env('SHORT_LINKS_CHECKER', \App\Services\CodeCheckers\EloquentCodeUniquenessChecker::class);

if (!class_exists($checker)) {
    throw new \InvalidArgumentException(
        "Класс проверки уникальности '{$checker}' не найден."
    );
}

if (!is_subclass_of($checker, CodeUniquenessChecker::class)) {
    throw new \InvalidArgumentException(
        "Класс '{$checker}' должен реализовывать интерфейс " . CodeUniquenessChecker::class
    );
}

return [
    'code_length' => $length,
    'checker' => $checker,
];

/*
Если вы заглянули сюда, значит это не спроста.
Почему длина кода от 4 до 10 символов.

Алфавит для кода: A-Z, a-z, 0-9 = 62 символа

Минимум 4 символа

62^3 = 238,328 Маловато, быстро закончатся
62^4 = 14,776,336 Минимум
62^5 = 916,132,832 Хорошо для средних проектов
62^6 = 56,800,235,584

С такой длиной работают bit.ly, tinyurl и проч.

Максимум 10 символов
62^8 ~218 триллионов (длина URL ~25 символов)
62^10 ~839 квинтиллионов (длина URL ~27 символов)
62^15 ~7 × 10^26 (длина URL ~32 символа)
62^20 ~7 × 10^35 (длина URL ~37 символов)

При 10+ символах URL становится длиннее части оригинальных ссылок, тогда теряется смысл "короткой ссылки".

Технически ограничений нет (почти).
Можно поставить 2 или 50. Laravel и БД разницы не заметят.
Но меньше 4 - риск коллизий, больше 10 - бессмысленно длинно.

Однако есть ограничение в БД - длина поля 255 символов, но это вопрос совместимости баз данных.
*/
